# Generate only QA project plumbing after Expo prebuild. Never edits app sources.
require 'xcodeproj'
require 'pathname'
root = Pathname.new(__dir__).parent
project_path = root.join('ios/ThumbleRewrite.xcodeproj')
project = Xcodeproj::Project.open(project_path)
app = project.targets.find { |t| t.name == 'ThumbleRewrite' } or abort 'Missing Expo app target'
name = 'NativePortalTests'
target = project.targets.find { |t| t.name == name }
unless target
  target = project.new_target(:unit_test_bundle, name, :ios, '17.0')
  target.add_dependency(app)
  group = project.main_group.new_group(name, '../tests/ios')
  target.source_build_phase.add_file_reference(group.new_file('NativePortalTests.swift'))
  resource = project.main_group.new_file('../../../packages/fixtures/controller-layout-v1.json')
  target.resources_build_phase.add_file_reference(resource)
end
# This resource contains only the ephemeral localhost QA port, never an invitation.
probe_config = root.join('tests/ios/AppProbeConfig.json')
probe_config.write('{"port":0}') unless probe_config.exist?
unless target.resources_build_phase.files.any? { |f| f.file_ref&.path&.end_with?('AppProbeConfig.json') }
  target.resources_build_phase.add_file_reference(project.main_group.new_file('../tests/ios/AppProbeConfig.json'))
end
# Ad-hoc simulator identity enables the real Keychain provider in the bundled QA app.
# These settings are simulator-only and generated by this QA script, never device signing.
app.build_configurations.each do |configuration|
  configuration.build_settings['CODE_SIGN_STYLE[sdk=iphonesimulator*]'] = 'Manual'
  configuration.build_settings['CODE_SIGN_IDENTITY[sdk=iphonesimulator*]'] = '-'
  configuration.build_settings['CODE_SIGN_ENTITLEMENTS[sdk=iphonesimulator*]'] = '../tests/ios/Simulator.entitlements'
end
target.build_configurations.each do |configuration|
  configuration.build_settings.merge!({
    'PRODUCT_NAME' => name,
    'PRODUCT_BUNDLE_IDENTIFIER' => 'com.codybontecou.thumble.rewrite.portal-tests',
    'GENERATE_INFOPLIST_FILE' => 'YES',
    'SWIFT_VERSION' => '6.0',
    'TEST_HOST' => '$(BUILT_PRODUCTS_DIR)/ThumbleRewrite.app/ThumbleRewrite',
    'BUNDLE_LOADER' => '$(TEST_HOST)',
    'CODE_SIGNING_ALLOWED' => 'NO',
    'SWIFT_INCLUDE_PATHS' => ['$(inherited)', *%w[ThumbleNativeInput MobileInputCore MobileInputUIKit ThumbleContracts].map { |m| "$(BUILT_PRODUCTS_DIR)/#{m}" }],
    'HEADER_SEARCH_PATHS' => ['$(inherited)'],
    'SWIFT_ENABLE_EXPLICIT_MODULES' => 'NO',
    'LD_RUNPATH_SEARCH_PATHS' => ['$(inherited)', '@executable_path/Frameworks', '@loader_path/Frameworks']
  })
end
project.save
scheme = Xcodeproj::XCScheme.new
scheme.add_build_target(app)
scheme.add_test_target(target)
scheme.set_launch_target(app)
scheme.test_action.build_configuration = 'Release'
scheme.save_as(project_path, name, true)
podfile = root.join('ios/Podfile')
contents = podfile.read
marker = "  # Thumble hosted UIKit tests"
unless contents.include?(marker)
  anchor = "  use_expo_modules!"
  abort 'Missing Expo Podfile anchor' unless contents.include?(anchor)
  contents.sub!(anchor, "#{anchor}\n#{marker}\n  target '#{name}' do\n    inherit! :search_paths\n  end")
  podfile.write(contents)
end
puts 'Prepared hosted native portal test target'

# A separate UI target drives the actual React route; old UIKit witnesses stay separate.
ui_name = 'SavedControllerUITests'
ui = project.targets.find { |t| t.name == ui_name }
unless ui
  ui = project.new_target(:ui_test_bundle, ui_name, :ios, '17.0')
  ui.add_dependency(app)
  group = project.main_group.new_group(ui_name, '../tests/ios')
  ui.source_build_phase.add_file_reference(group.new_file('SavedControllerUITests.swift'))
end
ui_probe = root.join('tests/ios/SavedControllerAppProbeConfig.json')
ui_probe.write('{"port":0,"mode":"none"}') unless ui_probe.exist?
unless ui.resources_build_phase.files.any? { |f| f.file_ref&.path&.end_with?('SavedControllerAppProbeConfig.json') }
  ui.resources_build_phase.add_file_reference(project.main_group.new_file('../tests/ios/SavedControllerAppProbeConfig.json'))
end
ui.build_configurations.each do |configuration|
  configuration.build_settings.merge!({
    'PRODUCT_NAME' => ui_name,
    'PRODUCT_BUNDLE_IDENTIFIER' => 'com.codybontecou.thumble.rewrite.saved-ui-tests',
    'GENERATE_INFOPLIST_FILE' => 'YES',
    'SWIFT_VERSION' => '6.0',
    'TEST_TARGET_NAME' => app.name,
    'CODE_SIGN_STYLE[sdk=iphonesimulator*]' => 'Manual',
    'CODE_SIGN_IDENTITY[sdk=iphonesimulator*]' => '-',
    'LD_RUNPATH_SEARCH_PATHS' => ['$(inherited)', '@executable_path/Frameworks', '@loader_path/Frameworks']
  })
end
project.root_object.attributes['TargetAttributes'] ||= {}
project.root_object.attributes['TargetAttributes'][ui.uuid] = { 'TestTargetID' => app.uuid }
project.save
ui_scheme = Xcodeproj::XCScheme.new
ui_scheme.add_build_target(app)
ui_scheme.add_test_target(ui)
ui_scheme.set_launch_target(app)
ui_scheme.test_action.build_configuration = 'Release'
ui_scheme.save_as(project_path, ui_name, true)
puts 'Prepared actual React saved-controller UI test target'
