#!/usr/bin/env python3
"""Generate portable skin text tables from the reviewed Swift runtime oracle."""
from pathlib import Path
import hashlib,json,urllib.request
ROOT=Path(__file__).resolve().parents[2]
manifest_path=ROOT/'Android/unicode/sources.json'
pinned=json.loads(manifest_path.read_text()) if manifest_path.exists() else None
sources={}
for version in ['16.0.0','17.0.0']:
 name=version+'/GraphemeBreakTest.txt'
 url='https://www.unicode.org/Public/'+version+'/ucd/auxiliary/GraphemeBreakTest.txt'
 path=ROOT/'Host/fixtures/unicode'/name
 if not path.exists():
  path.parent.mkdir(parents=True,exist_ok=True)
  with urllib.request.urlopen(url) as response:path.write_bytes(response.read())
 digest=hashlib.sha256(path.read_bytes()).hexdigest()
 if pinned and pinned['sources'][name]['sha256']!=digest:raise SystemExit('Source digest changed: '+name)
 sources[name]={'url':url,'sha256':digest}
native_path=ROOT/'Host/fixtures/unicode/native-text-oracle.json'
if not native_path.exists():raise SystemExit('Generate and copy testEmitAndroidSkinTextOracle first; see Android/unicode/README.md')
native=json.loads(native_path.read_text())
for version,value in native['datasets'].items():
 if value['sourceSHA256']!=sources[version+'/GraphemeBreakTest.txt']['sha256']:raise SystemExit('Native oracle uses different conformance inputs')
tables={name:[tuple(row) for row in values if name!='grapheme' or row[2] not in (12,13)] for name,values in native['segmentation'].items()}
for name in ['alphanumeric','control','whitespace']:tables[name]=[(lo,hi,1) for lo,hi in native['properties'][name]['ranges']]
output='''package com.thumble.android

// Generated by Android/scripts/generate-unicode-tables.py from Swift runtime probes.
// Source hashes, native conformance differences and license: Android/unicode/.
// Do not edit table data manually. Hangul syllables are classified algorithmically.
internal object SkinUnicodeData {
'''
for name,values in tables.items():
 encoded=' '.join(f'{lo:x}-{hi:x}-{prop:x}' for lo,hi,prop in values)
 chunks=[encoded[i:i+3000] for i in range(0,len(encoded),3000)]
 output+=f'    val {name}: IntArray by lazy {{ decode(\n'+ '\n        + '.join(json.dumps(c) for c in chunks)+'\n    ) }\n'
output+='''    private fun decode(value: String): IntArray = value.split(' ').flatMap { row ->
        row.split('-').map { it.toInt(16) }
    }.toIntArray()
}
'''
(ROOT/'Android/app/src/main/java/com/thumble/android/SkinUnicodeData.kt').write_text(output)
manifest={'fixtureVersion':1,'sources':sources,'nativeRuntimeSource':{'path':str(native_path.relative_to(ROOT)),'sha256':hashlib.sha256(native_path.read_bytes()).hexdigest()},'graphemeCodes':['Other','CR','LF','Control','Extend','ZWJ','RI','Prepend','SpacingMark','L','V','T','LV','LVT'],'indicCodes':['None','Consonant','Extend','Linker'],'generatedSHA256':hashlib.sha256(output.encode()).hexdigest(),'tableRanges':{k:len(v) for k,v in tables.items()}}
manifest_path.write_text(json.dumps(manifest,indent=2)+'\n')
license_path=ROOT/'Android/unicode/LICENSE.txt'
if not license_path.exists():
 with urllib.request.urlopen('https://www.unicode.org/license.txt') as response:license_path.write_bytes(response.read())
print(json.dumps({'ranges':manifest['tableRanges'],'generatedBytes':len(output.encode())}))
